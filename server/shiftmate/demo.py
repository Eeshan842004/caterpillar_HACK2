def lan_addresses() -> tuple[str | None, list[str]]:
    """(address of the default-route interface, all other IPv4 addresses). No packets are sent."""
    primary = None
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.connect(("10.254.254.254", 1))  # UDP connect only selects a route
        primary = probe.getsockname()[0]
    except OSError:
        pass
    finally:
        probe.close()
    others: list[str] = []
    try:
        for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
            ip = info[4][0]
            if ip != primary and not ip.startswith("127.") and ip not in others:
                others.append(ip)
    except OSError:
        pass
    if primary is None or primary.startswith("127."):
        primary = others.pop(0) if others else None
    return primary, others


def alembic_config():
    from alembic.config import Config

    cfg = Config(str(SERVER_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    return cfg


def migrate() -> str:
    """Brings the schema to head. A database with tables but no recorded revision (made by `seed`, or a half-run
    `alembic upgrade`) is stamped at head only if it already matches the models."""
    from alembic.runtime.migration import MigrationContext
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = alembic_config()
    tables = set(inspect(engine).get_table_names()) - {"alembic_version"}
    with engine.connect() as conn:
        revision = MigrationContext.configure(conn).get_current_revision()
    if tables and revision is None:
        # Tables but no recorded revision: created by `seed`/create_all, or a half-run `alembic upgrade`
        command.stamp(cfg, "head")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:
            raise SystemExit(
                "The existing database does not match the current schema. Delete it (server/var/shiftmate.db) "
                "and run the demo command again."
            ) from exc
        return "existing database adopted (stamped at head)"
    command.upgrade(cfg, "head")
    return "schema at head"


def status(db: Session) -> dict[str, Any]:
    counts = {
        "sites": db.query(Site).count(),
        "machines": db.query(Machine).count(),
        "operators": db.query(Operator).count(),
        "console_users": db.query(ConsoleUser).count(),
        "tasks": db.query(TaskAssignment).count(),
        "model_artifacts": db.query(ModelArtifact).count(),
        "paired_devices": db.query(Device).filter(Device.revoked_at.is_(None)).count(),
    }
    codes = [
        (p.code, p.machine_id, p.reusable, p.expires_at)
        for p in db.query(PairingCode).order_by(PairingCode.code)
    ]
    first_task = db.query(func.min(TaskAssignment.planned_date)).scalar()
    return {
        "counts": counts,
        "pairing_codes": codes,
        "first_task_date": first_task,
        "artifacts": [a.artifact_id for a in db.query(ModelArtifact).order_by(ModelArtifact.artifact_id)],
    }


def _static_line(label: str, path: str | None, url: str) -> str:
    if path and Path(path).is_dir():
        return f"  {label:<22}{url}"
    return f"  {label:<22}not served (set {'STATIC_OPERATOR_DIR' if 'app' in url else 'STATIC_CONSOLE_DIR'})"


