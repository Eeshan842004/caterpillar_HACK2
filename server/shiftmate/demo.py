def run(*, reset: bool, host: str, port: int, serve: bool, fleet: bool | None) -> None:
    print(f"Database: {migrate()}")
    db = SessionLocal()
    try:
        counts = reset_demo(db) if reset else seed_database(db)
        print(("Reset and re-seeded: " if reset else "Seeded (idempotent): ") + str(counts))
        info = status(db)
    finally:
        db.close()

    settings.CORS_ALLOW_LAN = True  # the tablet / LAN browsers call from their own origins
    if fleet is not None:
        settings.FLEET_SIM_ENABLED = fleet
    print(banner(port, info))
    if not serve:
        return

    import uvicorn

    from shiftmate.main import create_app  # built after the settings above are final

    uvicorn.run(create_app(), host=host, port=port, workers=1, log_level=settings.LOG_LEVEL)
